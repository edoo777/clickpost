// `fr` est déclaré `as const` pour permettre le typage strict des chemins pointés dans
// locale-provider.tsx (voir TranslationKey) — mais cela typerait chaque valeur avec son littéral
// français exact (`"Enregistrer"`), ce que `en.ts` ne pourrait jamais satisfaire. `Stringify`
// ramène chaque feuille à `string`, ne gardant que la FORME (les clés) comme contrat partagé.
type Stringify<T> = { [K in keyof T]: T[K] extends string ? string : Stringify<T[K]> };
export type Dictionary = Stringify<typeof fr>;
